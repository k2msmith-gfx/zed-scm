#!/usr/bin/env bash
# Regenerate the builtin-procedure pattern in languages/scm/highlights.scm from
# a live scm, so the list is what the binary actually binds rather than an
# R5RS list copied from another editor's queries. Names starting with `%` are
# the implementation's own helpers and are skipped: no text a user writes
# should colour as a builtin because the prelude needed a scratch procedure.
#
#   SCM=~/devel/scm/target/release/scm scripts/gen-builtins.sh          # splice
#   SCM=~/devel/scm/target/release/scm scripts/gen-builtins.sh --check  # CI
#
# The block is delimited by the BEGIN/END marker lines in the query file; the
# rest of the file is hand-written and untouched.
set -euo pipefail
cd "$(dirname "$0")/.."
SCM="${SCM:-scm}"
QUERY=languages/scm/highlights.scm
BEGIN=';; --- BEGIN generated by scripts/gen-builtins.sh ---'
END=';; --- END generated ---'

command -v "$SCM" >/dev/null 2>&1 || [ -x "$SCM" ] || {
  echo "gen-builtins: no scm at '$SCM'; set SCM=/path/to/scm" >&2; exit 2; }

names=$("$SCM" -e '(for-each (lambda (s) (display s) (newline)) (apropos ""))' \
        | grep -v '^%' | LC_ALL=C sort -u)
count=$(printf '%s\n' "$names" | wc -l | tr -d ' ')
version=$("$SCM" --version | awk '{print $2}')
# Escape what a tree-sitter #match? regex would otherwise read as syntax.
alternation=$(printf '%s\n' "$names" \
              | sed -E 's/[][(){}.*+?^$|\\\/]/\\\\&/g' \
              | paste -sd '|' -)

block=$(cat <<EOF
$BEGIN
;; $count procedures and variables bound by scm $version at startup, from
;; (apropos ""). Regenerate rather than edit. A builtin in head position is
;; a call; \`@function.builtin\` is preferred and falls back to \`@function\`
;; for themes that do not style it (Zed resolves fallbacks right-to-left).
(list
  .
  (symbol) @function @function.builtin
  (#match? @function.builtin
   "^($alternation)\$"))
$END
EOF
)

tmp=$(mktemp)
python3 - "$QUERY" "$BEGIN" "$END" "$block" > "$tmp" <<'PY'
import sys
path, begin, end, block = sys.argv[1:5]
lines = open(path).read().split('\n')
try:
    i = lines.index(begin); j = lines.index(end)
except ValueError:
    sys.exit(f"gen-builtins: {path} has no {begin!r}/{end!r} markers")
sys.stdout.write('\n'.join(lines[:i] + block.split('\n') + lines[j+1:]))
PY

if [ "${1:-}" = "--check" ]; then
  if cmp -s "$tmp" "$QUERY"; then echo "gen-builtins: $QUERY is current ($count names)"; rm -f "$tmp"
  else echo "gen-builtins: $QUERY is stale; run scripts/gen-builtins.sh" >&2; rm -f "$tmp"; exit 1; fi
else
  mv "$tmp" "$QUERY"; echo "gen-builtins: wrote $count names into $QUERY"
fi
